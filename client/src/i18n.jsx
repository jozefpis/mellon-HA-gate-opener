function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [locale, setLocaleState] = useState(
    () => localStorage.getItem(STORAGE_KEY) || 'en'
  );

  // If the user hasn't explicitly picked a locale, fall back to the server
  // default (DEFAULT_LOCALE env), fetched from /api/config.
  useEffect(() => {
    if (localStorage.getItem(STORAGE_KEY)) return;
    fetch('/api/config')
      .then((r) => r.json())
      .then((c) => {
        if (c.defaultLocale && DICT[c.defaultLocale]) setLocaleState(c.defaultLocale);
      })
      .catch(() => {});
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((l) => {
    localStorage.setItem(STORAGE_KEY, l);
    setLocaleState(l);
  }, []);

  const t = useCallback(
    (key, vars) =>
      interpolate((DICT[locale] && DICT[locale][key]) || DICT.en[key] || key, vars),
    [locale]
  );

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

export function LocaleSwitcher({ className = '' }) {
  const { locale, setLocale } = useI18n();
  return (
    <select
      className={`locale-switcher ${className}`}
      value={locale}
      onChange={(e) => setLocale(e.target.value)}
      aria-label="Language"
    >
      {LOCALES.map((l) => (
        <option key={l.code} value={l.code}>
          {l.name}
        </option>
      ))}
    </select>
  );
}
